import AppKit
import Combine
import CryptoKit
import ImageIO
import UniformTypeIdentifiers

/// One thing copied on this Mac, as out's clipboard history keeps it.
public struct ClipEntry: Codable, Identifiable, Equatable, Sendable {
    public enum Kind: String, Codable, Sendable { case text, image, files }
    public var id = UUID()
    /// When it was last copied: copying it again, or pasting it from the history, brings it up.
    public var date = Date()
    public var kind: Kind
    /// Text: its first `ClipboardHistory.previewLength` characters; files: their names, one a line;
    /// an image: empty.
    public var preview: String
    /// Text: its length in characters; files: how many there are; an image: 0.
    public var count: Int
    /// An image's size in pixels.
    public var width = 0
    public var height = 0
    /// What is kept of it, in bytes.
    public var bytes: Int
    /// The app it was copied in, by name and bundle identifier; empty when not known.
    public var app = ""
    public var bundle = ""
    /// Pinned: kept at the top, past the limits, until it is unpinned or removed.
    public var pinned = false
    /// What it holds, hashed: copying the same again brings this entry up instead of adding one.
    public var digest: String
}

/// What was copied on this Mac: text (with the formats it came in), images and files, kept in
/// `directory` (mode 0700), newest first, on this Mac alone. The clipboard is looked at twice a
/// second. Left out: what an app marks as concealed (a password), transient or generated
/// (nspasteboard.org, and the markers some password managers used before it), what out itself puts
/// there for a moment while it pastes, and what is copied in a password manager or in an app the
/// user named.
@MainActor
public final class ClipboardHistory: ObservableObject {
    /// What is kept and for how long; read each time the clipboard is looked at.
    public struct Policy: Equatable, Sendable {
        public var record: Bool
        /// Entries kept, pinned ones not counted.
        public var limit: Int
        /// Days an entry is kept for; 0 keeps it until the limit lets it go.
        public var days: Int
        /// Bundle identifiers of apps whose copies are not kept, besides `leftOutApps`.
        public var ignored: Set<String>
        public init(record: Bool = true, limit: Int = 200, days: Int = 30, ignored: Set<String> = []) {
            self.record = record; self.limit = limit; self.days = days; self.ignored = ignored
        }
    }

    public static let limits = [50, 200, 500, 1000]
    public static let dayChoices = [1, 7, 30, 0]
    public static let previewLength = 2000
    /// One copy is kept up to this many bytes: its formats in order of use, one that would go past
    /// it left out.
    public static let itemMax = 32 << 20
    /// All entries but the pinned ones, together, in bytes: the oldest go first past it.
    public static let totalMax = 1 << 30
    /// Markers of what is not for a clipboard history (nspasteboard.org; 1Password, KeeWeb,
    /// TypeIt4Me and others before it).
    public static let leftOutTypes: Set<String> = [
        "org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "Pasteboard generator type",
        "net.antelle.keeweb", "com.typeit4me.clipping",
    ]
    /// Apps whose copies are never kept: Passwords, Keychain Access and password managers.
    public static let leftOutApps: Set<String> = [
        "com.apple.Passwords", "com.apple.keychainaccess", "com.1password.1password", "com.agilebits.onepassword7",
        "com.agilebits.onepassword-osx", "com.bitwarden.desktop", "org.keepassxc.keepassxc", "com.lastpass.LastPass",
        "com.dashlane.Dashlane", "me.proton.pass.electron",
    ]

    /// Newest first.
    @Published public private(set) var entries: [ClipEntry] = []
    /// Nothing is kept while paused; what was copied meanwhile is not kept afterwards either.
    @Published public var paused = false {
        // A copy made while paused and not looked at yet is not kept on resuming.
        didSet { if oldValue, !paused { seen = board.changeCount } }
    }
    public var policy: @MainActor () -> Policy = { Policy() }
    /// Whether a change of the clipboard is out's own, for a moment (PasteboardLease).
    public var isOwn: @MainActor (Int) -> Bool = { _ in false }
    /// Told of each copy kept from the clipboard, a new one or one brought up again, with its files
    /// if it is files; not of an entry put back from the history.
    public var onKept: (@MainActor (ClipEntry, [URL]) -> Void)?
    /// The app in front, which is taken to be the one the copy was made in.
    public var frontApp: @MainActor () -> (bundle: String, name: String)? = {
        guard let app = NSWorkspace.shared.frontmostApplication else { return nil }
        return (app.bundleIdentifier ?? "", app.localizedName ?? "")
    }
    public let directory: URL
    private let board: NSPasteboard
    private var seen: Int
    private var timer: Timer?
    private var lastPolicy: Policy?
    private var pruned = Date.distantPast
    /// The app in front at the last look: a copy made just before another app came in front is
    /// seen after it has.
    private var lastFront: String?
    /// Writes and removals, in order, off the main thread; reads wait for them.
    private let io = DispatchQueue(label: "local.hopo.qingyan.clipboard", qos: .utility)

    /// A folder that cannot be made leaves the history empty: nothing can be kept in it.
    public init(directory: URL, board: NSPasteboard = .general) {
        self.directory = directory
        self.board = board
        seen = board.changeCount
        let files = FileManager.default
        try? files.createDirectory(at: directory, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
        try? files.setAttributes([.posixPermissions: 0o700], ofItemAtPath: directory.path)
        load()
    }

    public func start() {
        guard timer == nil else { return }
        seen = board.changeCount
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        timer.tolerance = 0.1
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    public func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// Looks at the clipboard once: what changed since the last look is kept, if it may be.
    public func check(now: Date = Date()) {
        let current = policy()
        // Just turned on: what changed since the last look was copied while it was off.
        let turnedOn = current.record && lastPolicy?.record == false
        if current != lastPolicy || now.timeIntervalSince(pruned) > 60 {
            lastPolicy = current
            prune(now: now)
        }
        let front = frontApp()
        let before = lastFront
        lastFront = front?.bundle
        let count = board.changeCount
        guard count != seen else { return }
        seen = count
        guard current.record, !turnedOn, !paused, !isOwn(count) else { return }
        capture(now: now, policy: current, front: front, before: before)
    }

    /// Waits for what is being written.
    public func flush() { io.sync {} }

    // MARK: Keeping

    private func capture(now: Date, policy: Policy, front: (bundle: String, name: String)?, before: String?) {
        guard let items = board.pasteboardItems, !items.isEmpty else { return }
        var types = Set<String>()
        for item in items { for type in item.types { types.insert(type.rawValue) } }
        guard types.isDisjoint(with: Self.leftOutTypes) else { return }
        // Not kept when any app it may have come from is left out: the one that says it put the
        // copy there (nspasteboard.org), the one in front, and the one in front at the last look.
        let source = items.first?.string(forType: .init("org.nspasteboard.source"))?.trimmingCharacters(in: .whitespacesAndNewlines) ?? ""
        let leftOut = Self.leftOutApps.union(policy.ignored)
        guard ![source, front?.bundle ?? "", before ?? ""].contains(where: { !$0.isEmpty && leftOut.contains($0) }) else { return }
        // The app that says it put the copy there is believed over the app in front.
        var app: (bundle: String, name: String) = front ?? (bundle: "", name: "")
        if !source.isEmpty, source != app.bundle { app = (source, Self.appName(source) ?? source) }
        var payload: [[String: Data]] = []
        var total = 0
        for item in items {
            var values: [String: Data] = [:]
            for type in Self.ordered(item.types) {
                guard let data = item.data(forType: type), total + data.count <= Self.itemMax else { continue }
                values[type.rawValue] = data
                total += data.count
            }
            if !values.isEmpty { payload.append(values) }
        }
        if let entry = keep(payload, app: app, at: now) { onKept?(entry, entry.kind == .files ? Self.fileURLs(payload) : []) }
    }

    /// Keeps what was copied; the same again brings its entry up. Returns the entry, or nil when it
    /// holds no text, image or file.
    @discardableResult
    func keep(_ payload: [[String: Data]], app: (bundle: String, name: String), at now: Date) -> ClipEntry? {
        guard var entry = Self.describe(payload) else { return nil }
        if let index = entries.firstIndex(where: { $0.digest == entry.digest }) {
            var known = entries.remove(at: index)
            known.date = now
            if !app.bundle.isEmpty || !app.name.isEmpty { known.app = app.name; known.bundle = app.bundle }
            write(payload, for: known.id)
            known.bytes = entry.bytes
            entries.insert(known, at: 0)
            saveIndex()
            return known
        }
        entry.date = now
        entry.app = app.name
        entry.bundle = app.bundle
        write(payload, for: entry.id, picture: entry.kind == .image ? Self.imageData(payload) : nil)
        entries.insert(entry, at: 0)
        prune(now: now)
        saveIndex()
        return entry
    }

    /// What a copy is, from its formats: files first, then text, then an image.
    static func describe(_ payload: [[String: Data]]) -> ClipEntry? {
        guard !payload.isEmpty else { return nil }
        let bytes = payload.reduce(0) { $0 + $1.values.reduce(0) { $0 + $1.count } }
        let urls = fileURLs(payload)
        if !urls.isEmpty {
            let names = urls.map(\.lastPathComponent)
            return ClipEntry(kind: .files, preview: names.joined(separator: "\n"), count: urls.count, bytes: bytes,
                             digest: digest("files", Data(urls.map(\.path).joined(separator: "\n").utf8)))
        }
        if let text = plainText(payload), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            return ClipEntry(kind: .text, preview: String(text.prefix(previewLength)), count: text.count, bytes: bytes,
                             digest: textDigest(payload))
        }
        if let image = imageData(payload) {
            var entry = ClipEntry(kind: .image, preview: "", count: 0, bytes: bytes, digest: digest("image", image))
            if let source = CGImageSourceCreateWithData(image as CFData, nil),
               let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any] {
                entry.width = (properties[kCGImagePropertyPixelWidth] as? NSNumber)?.intValue ?? 0
                entry.height = (properties[kCGImagePropertyPixelHeight] as? NSNumber)?.intValue ?? 0
            }
            return entry
        }
        return nil
    }

    private static func digest(_ kind: String, _ data: Data) -> String {
        var hash = SHA256()
        hash.update(data: Data(kind.utf8))
        hash.update(data: data)
        return hash.finalize().map { String(format: "%02x", $0) }.joined()
    }

    /// A text copy is the same as another when each of its items has the same text, rich text,
    /// HTML and link: two links that read alike but go to different places are two entries.
    private static func textDigest(_ payload: [[String: Data]]) -> String {
        var hash = SHA256()
        func add(_ data: Data) {
            withUnsafeBytes(of: UInt64(data.count).littleEndian) { hash.update(bufferPointer: $0) }
            hash.update(data: data)
        }
        add(Data("text".utf8))
        add(Data(String(payload.count).utf8))
        for values in payload {
            for type in [NSPasteboard.PasteboardType.string, .rtf, .html, .URL] { add(values[type.rawValue] ?? Data()) }
        }
        return hash.finalize().map { String(format: "%02x", $0) }.joined()
    }

    /// The formats of one item in the order they are kept: text and its rich forms, links and
    /// files, compressed pictures, then the rest, with TIFF (uncompressed) last, and not read at
    /// all beside a PNG or JPEG of the same picture.
    private static func ordered(_ types: [NSPasteboard.PasteboardType]) -> [NSPasteboard.PasteboardType] {
        let first: [NSPasteboard.PasteboardType] = [.string, .rtf, .html, .URL, .fileURL, .png, .init("public.jpeg")]
        let head = first.filter(types.contains)
        let tail = types.filter { !first.contains($0) && $0 != .tiff }
        let compressed = types.contains(.png) || types.contains(.init("public.jpeg"))
        return head + tail + (types.contains(.tiff) && !compressed ? [.tiff] : [])
    }

    static func plainText(_ payload: [[String: Data]]) -> String? {
        let texts = payload.compactMap { $0[NSPasteboard.PasteboardType.string.rawValue].flatMap { String(data: $0, encoding: .utf8) } }
        return texts.isEmpty ? nil : texts.joined(separator: "\n")
    }

    static func fileURLs(_ payload: [[String: Data]]) -> [URL] {
        payload.compactMap { values in
            values[NSPasteboard.PasteboardType.fileURL.rawValue]
                .flatMap { String(data: $0, encoding: .utf8) }
                .flatMap { URL(string: $0.trimmingCharacters(in: .controlCharacters)) }
        }.filter(\.isFileURL)
    }

    static func imageData(_ payload: [[String: Data]]) -> Data? {
        for type in [NSPasteboard.PasteboardType.png.rawValue, "public.jpeg", NSPasteboard.PasteboardType.tiff.rawValue] {
            if let data = payload.first?[type], !data.isEmpty { return data }
        }
        return nil
    }

    /// A small JPEG of a picture, for its row.
    private nonisolated static func thumbnail(_ image: Data) -> Data? {
        guard let source = CGImageSourceCreateWithData(image as CFData, nil) else { return nil }
        let options: [CFString: Any] = [kCGImageSourceCreateThumbnailFromImageAlways: true,
                                        kCGImageSourceCreateThumbnailWithTransform: true,
                                        kCGImageSourceThumbnailMaxPixelSize: 400]
        guard let small = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary) else { return nil }
        return NSBitmapImageRep(cgImage: small).representation(using: .jpeg, properties: [.compressionFactor: 0.7])
    }

    private static func appName(_ bundle: String) -> String? {
        guard let url = NSWorkspace.shared.urlForApplication(withBundleIdentifier: bundle) else { return nil }
        let name = FileManager.default.displayName(atPath: url.path)
        return name.hasSuffix(".app") ? String(name.dropLast(4)) : name
    }

    // MARK: Using

    /// Newest first with the pinned ones on top, those whose text, file names or app hold every
    /// word of `query` (case and accents aside).
    public func shown(matching query: String = "") -> [ClipEntry] {
        let words = query.split(whereSeparator: \.isWhitespace).map(String.init)
        let list = words.isEmpty ? entries : entries.filter { entry in
            words.allSatisfy { entry.preview.localizedStandardContains($0) || entry.app.localizedStandardContains($0) }
        }
        return list.filter(\.pinned) + list.filter { !$0.pinned }
    }

    /// Puts an entry back on the clipboard: in all the formats it came in, or as plain text alone
    /// (file entries as their paths, one a line). It comes up to the top; it is not kept again.
    @discardableResult
    public func put(_ entry: ClipEntry, plain: Bool = false, at now: Date = Date()) -> Bool {
        guard let payload = payload(entry.id) else { return false }
        board.clearContents()
        let done: Bool
        if plain, entry.kind != .image {
            let text = entry.kind == .files ? Self.fileURLs(payload).map(\.path).joined(separator: "\n") : (Self.plainText(payload) ?? entry.preview)
            done = board.setString(text, forType: .string)
        } else {
            let items = payload.map { values -> NSPasteboardItem in
                let item = NSPasteboardItem()
                for (type, data) in values { item.setData(data, forType: .init(type)) }
                return item
            }
            done = board.writeObjects(items)
        }
        seen = board.changeCount
        if done { touch(entry.id, at: now) }
        return done
    }

    /// The whole text of a text entry.
    public func text(_ entry: ClipEntry) -> String? {
        guard entry.kind == .text else { return nil }
        return payload(entry.id).flatMap(Self.plainText) ?? entry.preview
    }

    public func image(_ entry: ClipEntry) -> NSImage? {
        imageBytes(entry).flatMap(NSImage.init(data:))
    }

    /// An image entry's picture as it was copied: PNG, JPEG or TIFF.
    public func imageBytes(_ entry: ClipEntry) -> Data? {
        guard entry.kind == .image else { return nil }
        return payload(entry.id).flatMap(Self.imageData)
    }

    public func files(_ entry: ClipEntry) -> [URL] {
        guard entry.kind == .files else { return [] }
        return payload(entry.id).map(Self.fileURLs) ?? []
    }

    public func thumbnail(_ entry: ClipEntry) -> NSImage? {
        let url = thumbnailURL(entry.id)
        return io.sync { try? Data(contentsOf: url) }.flatMap(NSImage.init(data:))
    }

    public func touch(_ id: UUID, at now: Date = Date()) {
        guard let index = entries.firstIndex(where: { $0.id == id }) else { return }
        var entry = entries.remove(at: index)
        entry.date = now
        entries.insert(entry, at: 0)
        saveIndex()
    }

    public func pin(_ id: UUID, _ on: Bool) {
        guard let index = entries.firstIndex(where: { $0.id == id }), entries[index].pinned != on else { return }
        entries[index].pinned = on
        if !on { prune(now: Date()) }
        saveIndex()
    }

    public func remove(_ id: UUID) {
        guard let index = entries.firstIndex(where: { $0.id == id }) else { return }
        entries.remove(at: index)
        forget([id])
        saveIndex()
    }

    /// Removes every entry but the pinned ones, or every one.
    public func clear(pinnedToo: Bool = false) {
        let gone = entries.filter { pinnedToo || !$0.pinned }.map(\.id)
        guard !gone.isEmpty else { return }
        entries.removeAll { pinnedToo || !$0.pinned }
        forget(gone)
        saveIndex()
    }

    /// Lets go of what is past the limit, the days or the space; pinned entries stay.
    func prune(now: Date) {
        pruned = now
        let policy = lastPolicy ?? self.policy()
        var kept: [ClipEntry] = [], gone: [UUID] = []
        var unpinned = 0, bytes = 0
        for entry in entries {
            if entry.pinned { kept.append(entry); continue }
            let old = policy.days > 0 && now.timeIntervalSince(entry.date) > Double(policy.days) * 86_400
            if old || unpinned >= policy.limit || bytes + entry.bytes > Self.totalMax { gone.append(entry.id); continue }
            unpinned += 1
            bytes += entry.bytes
            kept.append(entry)
        }
        guard !gone.isEmpty else { return }
        entries = kept
        forget(gone)
        saveIndex()
    }

    // MARK: On disk

    private var indexURL: URL { directory.appendingPathComponent("index.json") }
    private func payloadURL(_ id: UUID) -> URL { directory.appendingPathComponent(id.uuidString + ".clip") }
    private func thumbnailURL(_ id: UUID) -> URL { directory.appendingPathComponent(id.uuidString + ".jpg") }

    private func payload(_ id: UUID) -> [[String: Data]]? {
        let url = payloadURL(id)
        guard let data = io.sync(execute: { try? Data(contentsOf: url) }) else { return nil }
        return Self.decode(data)
    }

    private static func decode(_ data: Data) -> [[String: Data]]? {
        (try? PropertyListSerialization.propertyList(from: data, format: nil)) as? [[String: Data]]
    }

    /// Writes a copy's formats and, for a picture, its thumbnail, off the main thread.
    private func write(_ payload: [[String: Data]], for id: UUID, picture: Data? = nil) {
        let url = payloadURL(id), small = thumbnailURL(id)
        io.async {
            guard let data = try? PropertyListSerialization.data(fromPropertyList: payload, format: .binary, options: 0) else { return }
            Self.save(data, to: url)
            if let picture, let thumbnail = Self.thumbnail(picture) { Self.save(thumbnail, to: small) }
        }
    }

    private nonisolated static func save(_ data: Data, to url: URL) {
        try? data.write(to: url, options: [.atomic])
        try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
    }

    private func forget(_ ids: [UUID]) {
        let urls = ids.flatMap { [payloadURL($0), thumbnailURL($0)] }
        io.async { for url in urls { try? FileManager.default.removeItem(at: url) } }
    }

    private struct Index: Codable { var entries: [ClipEntry] }

    private func saveIndex() {
        guard let data = try? JSONEncoder().encode(Index(entries: entries)) else { return }
        let url = indexURL
        io.async { Self.save(data, to: url) }
    }

    /// The entries whose kept copy is there, newest first; files no entry names are let go. An
    /// index that cannot be read is made again from the copies kept, without their pins and apps.
    private func load() {
        let files = FileManager.default
        let names = (try? files.contentsOfDirectory(atPath: directory.path)) ?? []
        if let data = try? Data(contentsOf: indexURL), let index = try? JSONDecoder().decode(Index.self, from: data) {
            entries = index.entries.filter { files.fileExists(atPath: payloadURL($0.id).path) }.sorted { $0.date > $1.date }
        } else {
            entries = names.compactMap { name -> ClipEntry? in
                guard (name as NSString).pathExtension == "clip", let id = UUID(uuidString: (name as NSString).deletingPathExtension),
                      let data = try? Data(contentsOf: payloadURL(id)), let payload = Self.decode(data),
                      var entry = Self.describe(payload) else { return nil }
                entry.id = id
                entry.date = (try? files.attributesOfItem(atPath: payloadURL(id).path))?[.modificationDate] as? Date ?? Date()
                return entry
            }.sorted { $0.date > $1.date }
            if !entries.isEmpty { saveIndex() }
        }
        let known = Set(entries.map(\.id.uuidString))
        for name in names where name != "index.json" {
            let stem = (name as NSString).deletingPathExtension
            if UUID(uuidString: stem) != nil, !known.contains(stem) { try? files.removeItem(at: directory.appendingPathComponent(name)) }
        }
    }
}
